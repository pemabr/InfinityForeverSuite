local cachedLanguage
local reverse

local function DetectLanguage()
    local db = GuildTradeCenterDB
    local choice = type(db) == "table" and db.language or nil
    if choice == "de" or choice == "en" then
        return choice
    end
    local locale = type(GetLocale) == "function" and GetLocale() or "enUS"
    return locale == "deDE" and "de" or "en"
end

function GTC.GetLanguage()
    if not cachedLanguage then
        local detected = DetectLanguage()
        -- Erst merken, wenn die gespeicherten Einstellungen geladen sind. Ein frueher
        -- Aufruf haette sonst die per /gtc lang gewaehlte Sprache fuer die ganze Sitzung
        -- uebergangen.
        if type(GuildTradeCenterDB) ~= "table" then
            return detected
        end
        cachedLanguage = detected
    end
    return cachedLanguage
end

-- Setzt die Sprache ("de", "en" oder nil/"auto"). Die Anzeige aendert sich nach /reload.
function GTC.SetLanguage(code)
    local db = GuildTradeCenterDB
    if type(db) ~= "table" then return false end
    if code == "de" or code == "en" then
        db.language = code
    else
        db.language = nil
    end
    cachedLanguage = nil
    return true
end

-- Liefert die Anzeige-Variante eines Textes (Deutsch = unveraendert).
function GTC.T(text)
    if GTC.GetLanguage() == "en" then
        return GTC.EN[text] or text
    end
    return text
end

-- Gegenstueck zu T: ermittelt aus einem (englischen) Anzeigetext wieder den deutschen Schluessel,
-- auch bei dynamischen Texten mit Zahlen am Ende ("Quality (3)" -> "Qualit\195\164t (3)").
function GTC.Untranslate(text)
    if type(text) ~= "string" or GTC.GetLanguage() ~= "en" then
        return text
    end
    if not reverse then
        reverse = {}
        for german, english in pairs(GTC.EN) do
            if reverse[english] == nil or #german < #reverse[english] then
                reverse[english] = german
            end
        end
    end
    if reverse[text] then
        return reverse[text]
    end
    local bestEnglish
    for english in pairs(reverse) do
        if #english >= 4 and #english > #(bestEnglish or "") and text:sub(1, #english) == english then
            bestEnglish = english
        end
    end
    if bestEnglish then
        return reverse[bestEnglish] .. text:sub(#bestEnglish + 1)
    end
    return text
end
